"""Write a human-readable data-quality report in Markdown.

The report is regenerated on every run and committed, so a reviewer can see in
a git diff when new data changes the counts (for example, a jump in flagged
parcels after the county publishes a new roll).
"""

from pathlib import Path

import pandas as pd

from zce.config import CityConfig

FLAG_MEANINGS = {
    "outside_city_limits": "Tax-rate city is this city but the lot's interior point is outside the city boundary layer (usually edge misalignment).",
    "no_zone": "No zone found for the lot (no zoning polygon overlaps it, or its parcel number isn't in the zoning table). Capacity cannot be computed.",
    "split_zoned": "The largest zone covers less than 90% of the lot (split zoning or line misalignment).",
    "specific_plan_simplified": "Lot is in a specific plan; its rules are simplified in the MVP.",
    "planned_development": "Lot is in a Planned Development (PD) with its own custom ordinance; not modeled in the MVP.",
    "overlay_unparsed": "The overlay field had text we did not recognize (listed below).",
    "missing_building_data": "Assessor has no building record (often vacant, public, or exempt land). Existing units unknown.",
    "missing_assessed_value": "No land/improvement value on the roll (often exempt or public land).",
    "sliver_lot": "Lot is under 500 sq ft; probably a strip or mapping artifact.",
}


def _table(df: pd.DataFrame) -> str:
    """Render a small DataFrame as a Markdown table (no extra dependency)."""
    cols = [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(str(v) for v in row) + " |")
    return "\n".join(lines)


def write_quality_report(
    parcels, zones, stats: dict, manifest: dict, city: CityConfig, path: Path, zoning_notes: list[str] = ()
) -> None:
    n = len(parcels)
    out: list[str] = [f"# Data quality report: {city.name}", ""]
    out.append("Generated by `make clean`. Do not edit by hand.\n")

    out.append("## Sources\n")
    out.append(_table(pd.DataFrame(
        [{"source": k, "downloaded (UTC)": v["downloaded_at"], "size": next((f"{v[k]:,} {k}" for k in ("features", "records", "bytes") if k in v), ""),
          "publisher": v["publisher"]} for k, v in manifest.items()]
    )))

    out.append("\n## Parcels\n")
    out.append(f"- Assessor records: **{stats['assessor_records']:,}**")
    out.append(f"- Condo unit records merged into their lot: **{stats['condo_records_merged']:,}** "
               f"(into {stats['condo_lots']:,} condo lots)")
    out.append(f"- Lots after merge: **{n:,}** (none dropped; every lot below is counted)")
    out.append(f"- Existing housing units on the roll: **{int(parcels['existing_units'].sum()):,}**. "
               "Compared with the state's official count in validation.md.")
    out.append(f"- Total lot area: **{parcels['lot_area_sqft'].sum() / 43560:,.0f} acres**")

    out.append("\n## Flags\n")
    out.append("A lot can have several flags. Flagged lots are kept and shown on the map with a warning.\n")
    counts = parcels["flags"].explode().value_counts()
    flag_rows = [{"flag": f"`{f}`", "lots": f"{int(counts.get(f, 0)):,}",
                  "share": f"{counts.get(f, 0) / n:.1%}", "meaning": m} for f, m in FLAG_MEANINGS.items()]
    out.append(_table(pd.DataFrame(flag_rows)))
    unflagged = (parcels["flags"].map(len) == 0).sum()
    out.append(f"\nLots with no flags: **{unflagged:,}** ({unflagged / n:.1%})")

    out.append("\n## Lots by zone category\n")
    by_cat = parcels.groupby(parcels["zone_category"].fillna("(no zone)")).agg(
        lots=("parcel_id", "size"),
        acres=("lot_area_sqft", lambda s: s.sum() / 43560),
        existing_units=("existing_units", "sum"),
    ).sort_values("acres", ascending=False)
    by_cat["acres"] = by_cat["acres"].round(0).astype(int)
    by_cat["existing_units"] = by_cat["existing_units"].astype(int)
    out.append(_table(by_cat.reset_index()))

    # Headline-number preview. "Residential land" here = lots in single-family
    # or multi-family base zones; specific plans are excluded until M3 rule
    # files tell us which of their districts allow housing.
    res = parcels["zone_category"].isin(["Single-Family Residential", "Multi-Family Residential"])
    sf = parcels["zone_category"] == "Single-Family Residential"
    sf_share = parcels.loc[sf, "lot_area_sqft"].sum() / parcels.loc[res, "lot_area_sqft"].sum()
    out.append(f"\n**Preview:** single-family zones are **{sf_share:.0%}** of the lot area in "
               "residential base zones (excluding specific plans and PDs, which are counted after M3).")

    out.append("\n## Zone codes\n")
    by_zone = parcels.groupby(parcels["zone_code"].fillna("(none)")).agg(
        lots=("parcel_id", "size"), acres=("lot_area_sqft", lambda s: round(s.sum() / 43560))
    ).sort_values("lots", ascending=False)
    out.append(f"{len(by_zone)} distinct zone codes on lots. Top 25 by lot count (these need rule files first):\n")
    out.append(_table(by_zone.head(25).reset_index()))

    out.append("\n## Specific plans\n")
    sp = parcels.groupby(parcels["specific_plan"].fillna("(none)")).agg(
        lots=("parcel_id", "size"), acres=("lot_area_sqft", lambda s: round(s.sum() / 43560)),
        existing_units=("existing_units", lambda s: int(s.sum())))
    out.append(_table(sp.sort_values("lots", ascending=False).reset_index()))

    out.append("\n## Overlays\n")
    ov = parcels["overlays"].explode().dropna().value_counts()
    out.append(_table(pd.DataFrame({"overlay": ov.index, "lots": ov.values}).head(30)))
    unparsed = zones.loc[zones["overlay_unparsed"].fillna("") != "", "overlay_unparsed"].value_counts()
    if len(unparsed):
        out.append("\nUnrecognized overlay text in the zoning layer (review by hand):\n")
        out.extend(f"- `{t}` ({c} polygons)" for t, c in unparsed.items())

    # Notes from the zoning adapter: e.g. polygons whose category label doesn't
    # match their code (a data error to report to the city), or lots SCAG's
    # table didn't cover.
    if zoning_notes:
        out.append("\n## Zoning data notes\n")
        out.extend(f"- {n}" for n in zoning_notes)

    out.append("\n## Distance to transit\n")
    out.append("Measured from the lot's edge to the nearest stop (see `transit.distance_to_nearest_ft`).\n")
    within = (parcels["dist_major_transit_ft"] <= 2640).sum()
    out.append(f"- Lots within ½ mile (2,640 ft) of a major transit stop: **{within:,}** ({within / n:.1%}). "
               "AB 2097 parking relief applies to these.")
    out.append(f"- Median distance to a Metro rail station: {parcels['dist_rail_station_ft'].median():,.0f} ft")
    out.append(f"- Lots with no distance (should be 0): {parcels['dist_major_transit_ft'].isna().sum():,}")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
