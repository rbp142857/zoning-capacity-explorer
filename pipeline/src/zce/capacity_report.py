"""Markdown summary of capacity results (reports/<city>/capacity_report.md).

Regenerated by `make capacity` and committed, so changes to a rule file
show up in git as changes to the totals.
"""

from pathlib import Path

import pandas as pd

from zce.config import CityConfig
from zce.report import _table

BINDING_MEANINGS = {
    "density": "A flat cap on units per lot or per acre",
    "lot_area_per_unit": "Each unit needs a minimum slice of the lot",
    "envelope": "Setbacks, height, coverage, gardens or floor-area limits leave too little building",
    "parking": "Required surface parking takes the room",
    "use_not_permitted": "Zoning doesn't allow housing here",
    "state_law:sb9": "State law SB 9 allows more than local zoning (2 units, or 4 with a lot split)",
    "state_law:adu": "State ADU law allows more than local zoning (house + ADU + junior ADU)",
}


def _fmt(n) -> str:
    return f"{int(n):,}"


def write_capacity_report(df: pd.DataFrame, rules: dict, state, city: CityConfig, path: Path) -> None:
    n = len(df)
    ok = df[df["model_status"] == "ok"]
    not_modeled = df[df["model_status"] != "ok"]
    out = [f"# Capacity report: {city.name}", "", "Generated by `make capacity`. Do not edit by hand.", ""]
    out.append("> Estimates for research and advocacy, not legal or zoning advice. "
               "These are *theoretical* maximums under the rules as modeled; most lots will never be rebuilt "
               "(see the realistic estimate in milestone 7).\n")

    out.append("## Headline numbers\n")
    out.append(f"- Lots: **{_fmt(n)}**; modeled: **{_fmt(len(ok))}** ({len(ok) / n:.1%}); "
               f"not yet modeled: **{_fmt(len(not_modeled))}** (specific-plan-only districts and planned developments)")
    out.append(f"- Existing homes on modeled lots: **{_fmt(ok['existing_units'].sum())}**")
    out.append(f"- Maximum legal homes on modeled lots, **local zoning only**: **{_fmt(ok['local_units'].sum())}**")
    out.append(f"- Maximum legal homes **with state law** (SB 9, ADUs, AB 2097): **{_fmt(ok['max_units'].sum())}**")
    out.append(f"- Net new capacity (max legal minus existing, never below 0 per lot): **{_fmt(ok['net_new_units'].sum())}**")

    res = ok[ok["rules_zone"].map(lambda z: rules[z].residential_allowed.value if z in rules else False)]
    one_unit = res["local_units"] <= 1
    share = res.loc[one_unit, "lot_area_sqft"].sum() / res["lot_area_sqft"].sum()
    out.append(f"- Share of residential land where **local zoning allows only one home**: **{share:.0%}** "
               "(before state law; with SB 9 and ADU law almost none of it is limited to one home)\n")

    out.append("## What limits capacity (binding constraint)\n")
    by_bind = ok.groupby("binding_constraint").agg(
        lots=("parcel_id", "size"), max_units=("max_units", "sum"), net_new=("net_new_units", "sum")
    ).sort_values("lots", ascending=False)
    by_bind["meaning"] = by_bind.index.map(lambda b: BINDING_MEANINGS.get(b, ""))
    out.append(_table(by_bind.reset_index()))

    out.append("\nUnder **local zoning alone** (before state law):\n")
    by_local = ok.groupby("local_binding_constraint").agg(
        lots=("parcel_id", "size"), local_units=("local_units", "sum")
    ).sort_values("lots", ascending=False)
    out.append(_table(by_local.reset_index()))

    out.append("\n## By zone\n")
    by_zone = ok.groupby("rules_zone").agg(
        lots=("parcel_id", "size"),
        existing=("existing_units", lambda s: int(s.sum())),
        local_max=("local_units", "sum"),
        max_with_state_law=("max_units", "sum"),
        net_new=("net_new_units", "sum"),
    ).sort_values("lots", ascending=False)
    out.append(_table(by_zone.reset_index()))

    out.append("\n## By council district\n")
    by_d = ok.groupby(ok["district"].fillna("(none)")).agg(
        lots=("parcel_id", "size"), existing=("existing_units", lambda s: int(s.sum())),
        max_with_state_law=("max_units", "sum"), net_new=("net_new_units", "sum"))
    out.append(_table(by_d.reset_index()))

    out.append("\n## By distance to a major transit stop\n")
    bins = [0, 1320, 2640, 5280, float("inf")]
    labels = ["< ¼ mile", "¼–½ mile", "½–1 mile", "> 1 mile"]
    band = pd.cut(ok["dist_major_transit_ft"], bins=bins, labels=labels, right=False)
    by_t = ok.groupby(band, observed=False).agg(
        lots=("parcel_id", "size"), max_with_state_law=("max_units", "sum"), net_new=("net_new_units", "sum"))
    out.append(_table(by_t.reset_index().rename(columns={"dist_major_transit_ft": "distance"})))

    out.append("\n## State law\n")
    for law in state.laws:
        applied = ok["state_laws_applied"].map(lambda xs: law.id in list(xs)).sum()
        status = f"applied on {_fmt(applied)} lots" if law.status == "modeled" else "**not modeled** (capacity is underestimated)"
        out.append(f"- **{law.name}** ({law.citation.section}): {status}")

    out.append("\n## Not modeled yet\n")
    nm = not_modeled.groupby(not_modeled["zone_code"].fillna("(no zone)")).agg(
        lots=("parcel_id", "size"), existing=("existing_units", lambda s: int(s.sum()))
    ).sort_values("lots", ascending=False)
    out.append(f"{_fmt(len(not_modeled))} lots in {len(nm)} zone codes, holding "
               f"{_fmt(not_modeled['existing_units'].sum())} existing homes. Top 15:\n")
    out.append(_table(nm.head(15).reset_index()))

    out.append("\n## Simplification flags on modeled lots\n")
    flags = ok["capacity_flags"].explode().dropna().value_counts()
    out.append(_table(pd.DataFrame({"flag": [f"`{f}`" for f in flags.index], "lots": flags.values})))

    out.append("\n## Assumptions\n")
    a = city.assumptions
    out.append(f"- Average new unit: {a.avg_unit_net_sqft:,.0f} sf inside the unit; {a.net_to_gross:.0%} of building "
               f"floor area is inside units, so each unit uses {a.gross_sqft_per_unit:,.0f} sf of building")
    out.append(f"- Parking: {a.parking_mode} parking, {a.parking_stall_sqft:,.0f} sf of ground per stall including aisles")
    out.append("- Every zone-specific assumption is written next to its value in `cities/pasadena/rules/*.yaml`.")

    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n")
